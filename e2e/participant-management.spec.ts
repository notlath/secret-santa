import { expect, loseNextActionResponse, test } from "./fixtures"
import { createExchange } from "./helpers"

test("Host re-issues a Personal Link and the old link and cookie stop working", async ({ page, browser }) => {
  const { accessCode } = await createExchange(page)
  await page.getByRole("checkbox", { name: "I've saved my Host Link" }).check()
  await page.getByRole("link", { name: "Go to the dashboard" }).click()
  const device = await browser.newContext()
  const friend = await device.newPage()
  await friend.goto(`/join/${accessCode}`)
  await friend.getByLabel("Display name").fill("Ben")
  await friend.getByRole("button", { name: "Join" }).click()
  const oldLink = await friend.getByRole("textbox", { name: "Personal Link" }).inputValue()
  await friend.getByRole("link", { name: "Go to my page" }).click()
  const participantPage = friend.url()
  await page.reload()
  await page.getByRole("button", { name: "Re-issue link for Ben" }).click()
  await expect(page.getByText("New Personal Link for Ben. The old link no longer works.")).toBeVisible()
  await page.context().grantPermissions(["clipboard-read", "clipboard-write"])
  await page.getByRole("button", { name: "Copy new Personal Link" }).click()
  const newLink = await page.evaluate(() => navigator.clipboard.readText())
  expect(newLink).not.toBe(oldLink)
  await friend.goto(participantPage)
  await expect(friend.getByRole("heading", { name: "This link no longer works" })).toBeVisible()
  await friend.goto(oldLink)
  await expect(friend.getByText("Ask your Host for a new one.")).toBeVisible()
  const fresh = await browser.newContext()
  const newDevice = await fresh.newPage()
  await newDevice.goto(newLink)
  await expect(newDevice.getByText("You're in as Ben")).toBeVisible()
  await loseNextActionResponse(page)
  await page.getByRole("button", { name: "Re-issue link for Ben" }).click()
  await expect(page.getByText("The link may have changed. Re-issue it again to get a working link.")).toBeVisible()
  await expect(page.getByRole("button", { name: "Copy new Personal Link" })).toHaveCount(0)
  await newDevice.goto(newLink)
  await expect(newDevice.getByRole("heading", { name: "This link no longer works" })).toBeVisible()
  await page.getByRole("button", { name: "Re-issue link for Ben" }).click()
  await page.getByRole("button", { name: "Copy new Personal Link" }).click()
  const recoveredLink = await page.evaluate(() => navigator.clipboard.readText())
  await newDevice.goto(recoveredLink)
  await expect(newDevice.getByText("You're in as Ben")).toBeVisible()
  await fresh.close()
  await device.close()
})

test("Host confirms removal before the Participant loses access", async ({ page, browser }) => {
  const { accessCode } = await createExchange(page)
  await page.getByRole("checkbox", { name: "I've saved my Host Link" }).check()
  await page.getByRole("link", { name: "Go to the dashboard" }).click()
  const device = await browser.newContext()
  const friend = await device.newPage()
  await friend.goto(`/join/${accessCode}`)
  await friend.getByLabel("Display name").fill("Ben")
  await friend.getByRole("button", { name: "Join" }).click()
  const personalLink = await friend.getByRole("textbox", { name: "Personal Link" }).inputValue()
  await page.reload()
  await page.getByRole("button", { name: "Remove Ben" }).click()
  await expect(page.getByRole("alertdialog")).toContainText("Their Wishlist will be deleted")
  await page.getByRole("button", { name: "Cancel" }).click()
  await expect(page.getByRole("button", { name: "Remove Ben" })).toBeVisible()
  await page.getByRole("button", { name: "Remove Ben" }).click()
  await page.getByRole("button", { name: "Remove Participant" }).click()
  await expect(page.getByText("Nobody has joined yet.")).toBeVisible()
  await friend.goto(personalLink)
  await expect(friend.getByRole("heading", { name: "This link no longer works" })).toBeVisible()
  await device.close()
})
